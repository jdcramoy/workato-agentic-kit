#!/usr/bin/env bash
# onboard.sh — interactive first-run questionnaire for the agentic-workato-kit.
# Asks what install.sh needs, validates shapes, writes config.sh, then offers
# to install. Never runs install.sh without you pressing return on the last
# question. Re-run any time: existing config.sh values are the defaults.

set -euo pipefail
cd "$(dirname "$0")"

EXISTING=""
[ -f config.sh ] && EXISTING="$(cat config.sh)"

answer() { # answer <var> <question> <default> <validator> <fail-msg>
  local var="$1" q="$2" def="$3" validator="$4" fail="$5" v="" n=0
  while true; do
    n=$((n + 1))
    if [ "$n" -gt 3 ]; then
      echo "  ✗ too many invalid attempts — fix config.sh by hand or re-run ./onboard.sh" >&2
      exit 1
    fi
    printf "\n%s" "$q"
    [ -n "$def" ] && printf " [%s]" "$def"
    printf ": "
    # EOF (piped/closed stdin) takes the default rather than spinning forever
    if ! read -r v; then
      printf -v "$var" '%s' "$def"
      break
    fi
    [ -z "$v" ] && v="$def"
    if [ -z "$validator" ] || bash -c "echo \"$v\" | grep -qE \"$validator\"" 2>/dev/null; then
      printf -v "$var" '%s' "$v"; break
    fi
    echo "  ✗ $fail"
  done
}

optional() { # optional <var> <question> <default> — blank allowed
  local var="$1" q="$2" def="$3" v=""
  printf "\n%s" "$q"
  [ -n "$def" ] && printf " [%s]" "$def"
  printf ": "
  if ! read -r v; then v="$def"; fi
  [ -z "$v" ] && v="$def"
  printf -v "$var" '%s' "$v"
}

echo "== agentic-workato-kit onboarding =="
echo "Answers become config.sh (nothing is sent anywhere)."
echo "Press return to accept the [default]."
echo

echo "-- Workato workspaces (Settings → Workspace in each environment) --"
answer WORKSPACE_DEV  "Dev workspace ID (digits):"            "" '^[0-9]+$' "workspace IDs are digits"
answer WORKSPACE_PROD "Prod workspace ID (digits, blank = no prod wrappers):" "" '^[0-9]*$' "workspace IDs are digits"
answer ENV_DEV_NAME   "Dev environment label:"   "Development [${WORKSPACE_DEV}]" "" ""
answer ENV_PROD_NAME  "Prod environment label:"  "Production [${WORKSPACE_PROD}]" "" ""

echo
echo "-- Jira (promotion stories + the story-points gate) --"
answer JIRA_CLOUD_ID "Jira cloud ID (UUID from your site URL / admin):" "" '^[0-9a-fA-F-]{8,}$' "cloud IDs are UUID-shaped"
answer JIRA_PROJECT  "Jira project key for deployment stories:" "BSYS" '^[A-Z]{2,6}$' "project keys are 2-6 CAPITAL letters"
answer GOVERNING_EPIC "Governing epic for deployment stories (KEY-123, blank = skip):" "" '^[A-Z]{2,6}-[0-9]+$|^$' "epic looks like KEY-12345"
answer FIELD_MANIFEST "Manifest URL field id:"    "" '^customfield_[0-9]+$|^$' "field ids look like customfield_12345"
answer FIELD_ENV_CASCADE "Target-env cascade field id:" "" '^customfield_[0-9]+$|^$' "field ids look like customfield_12345"
answer FIELD_SOURCE_ENV "Source-env field id:"    "" '^customfield_[0-9]+$|^$' "field ids look like customfield_12345"
answer FIELD_POINTS  "Story-points field id:"     "customfield_10057" '^customfield_[0-9]+$' "field ids look like customfield_12345"

echo
echo "-- CLI profiles + harness backup --"
answer PROFILE_DEV  "Dev CLI profile name:"  "dev"  '^[a-zA-Z0-9_-]+$' "profile names are simple strings"
answer PROFILE_PROD "Prod CLI profile name:" "prod" '^[a-zA-Z0-9_-]+$' "profile names are simple strings"
optional BACKUP_REPO_LOCAL "Harness backup: local repo dir (blank = skip backup):" ""
optional BACKUP_REPO_URL   "Harness backup: origin URL (blank = local-only commits):" ""

PROJECT_PATH_DEFAULT="${PROJECT_PATH:-${HOME}/Documents/workbench}"
optional PROJECT_PATH "Project dir where the agents/crons live:" "$PROJECT_PATH_DEFAULT"

# --- write config.sh ----------------------------------------------------------
{
  echo "#!/usr/bin/env bash"
  echo "# agentic-workato-kit — generated by onboard.sh $(date '+%Y-%m-%d %H:%M')"
  echo ": \"\${KIT_HOME:=\${HOME}}\"   # only set if not already in the environment"
  echo
  echo "export WORKSPACE_DEV=\"${WORKSPACE_DEV}\""
  echo "export WORKSPACE_PROD=\"${WORKSPACE_PROD}\""
  echo "export ENV_DEV_NAME=\"${ENV_DEV_NAME}\""
  echo "export ENV_PROD_NAME=\"${ENV_PROD_NAME}\""
  echo
  echo "export JIRA_CLOUD_ID=\"${JIRA_CLOUD_ID}\""
  echo "export JIRA_PROJECT=\"${JIRA_PROJECT}\""
  echo "export GOVERNING_EPIC=\"${GOVERNING_EPIC}\""
  echo "export FIELD_MANIFEST=\"${FIELD_MANIFEST}\""
  echo "export FIELD_ENV_CASCADE=\"${FIELD_ENV_CASCADE}\""
  echo "export FIELD_SOURCE_ENV=\"${FIELD_SOURCE_ENV}\""
  echo "export FIELD_POINTS=\"${FIELD_POINTS}\""
  echo
  echo "export PROFILE_DEV=\"${PROFILE_DEV}\""
  echo "export PROFILE_PROD=\"${PROFILE_PROD}\""
  echo
  echo "export BACKUP_REPO_LOCAL=\"${BACKUP_REPO_LOCAL}\""
  echo "export BACKUP_REPO_URL=\"${BACKUP_REPO_URL}\""
  echo
  echo "export PROJECT_PATH=\"${PROJECT_PATH}\""
} > config.sh
chmod 600 config.sh

echo
echo "== config.sh written (chmod 600) =="
echo "  dev ws: ${WORKSPACE_DEV} | prod ws: ${WORKSPACE_PROD:-none}"
echo "  jira: ${JIRA_PROJECT} @ ${JIRA_CLOUD_ID}"
echo "  backup: ${BACKUP_REPO_LOCAL:-skipped}"
printf "\nRun ./install.sh now? [Y/n]: "
read -r GO
[ "${GO:-Y}" = "Y" ] && exec ./install.sh
echo "config saved. Run ./install.sh when ready."
